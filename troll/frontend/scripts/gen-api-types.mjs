#!/usr/bin/env node
// Hand-rolled OpenAPI-schemas -> TypeScript-interfaces generator (Story 15.1 Task 3, AD-F5:
// "generated, never hand-written"). Deliberately NOT a dependency: converts only
// components.schemas (the Pydantic response models data_api's routes declare) into named
// TS interfaces -- this project's modest, slow-growing API surface doesn't warrant a full
// OpenAPI-to-TS compiler as a dependency; a ~50-line script covers it and has no peer-dep
// coupling to whatever TypeScript version this project happens to pin. Extend this script,
// not swap in a library, if a future story's schema needs a shape this doesn't yet handle.
//
// Usage: node scripts/gen-api-types.mjs <openapi.json> <output.ts>

import { readFileSync, writeFileSync } from "node:fs";

const PRIMITIVE_TYPES = {
  string: "string",
  integer: "number",
  number: "number",
  boolean: "boolean",
  // Pydantic Optional[T]/T | None fields render as anyOf: [{type: T}, {type: "null"}] --
  // without this, tsType() fell through to "unknown", and TS collapses `T | unknown` to
  // plain `unknown`, silently erasing type-checking for every nullable field (caught in
  // code review, verified via a minimal repro schema before fixing).
  null: "null",
};

// Schemas FastAPI adds automatically for its own error responses -- not part of this app's
// actual data contract, so not worth generating a type for.
const SKIP_SCHEMAS = new Set(["HTTPValidationError", "ValidationError"]);

function tsType(schema) {
  if (!schema) return "unknown";
  if (schema.$ref) return schema.$ref.split("/").pop();
  if (schema.anyOf) return schema.anyOf.map(tsType).join(" | ");
  if (schema.type === "array") return `${tsType(schema.items)}[]`;
  if (schema.type === "object") {
    if (schema.additionalProperties && schema.additionalProperties !== true) {
      return `Record<string, ${tsType(schema.additionalProperties)}>`;
    }
    return "Record<string, unknown>";
  }
  return PRIMITIVE_TYPES[schema.type] ?? "unknown";
}

function genInterface(name, schema) {
  const required = new Set(schema.required ?? []);
  const props = Object.entries(schema.properties ?? {})
    .map(([key, propSchema]) => `  ${key}${required.has(key) ? "" : "?"}: ${tsType(propSchema)};`)
    .join("\n");
  return `export interface ${name} {\n${props}\n}`;
}

const [, , inputPath, outputPath] = process.argv;
if (!inputPath || !outputPath) {
  console.error("Usage: node gen-api-types.mjs <openapi.json> <output.ts>");
  process.exit(1);
}

const openapi = JSON.parse(readFileSync(inputPath, "utf-8"));
const schemas = openapi.components?.schemas ?? {};
const interfaces = Object.entries(schemas)
  .filter(([name]) => !SKIP_SCHEMAS.has(name))
  .map(([name, schema]) => genInterface(name, schema))
  .join("\n\n");

const header =
  "// AUTO-GENERATED by frontend/scripts/gen-api-types.mjs from data_api's OpenAPI schema.\n" +
  "// Do not hand-edit -- regenerate via `npm run codegen` (see that script's own docs).\n\n";

writeFileSync(outputPath, header + interfaces + "\n");
console.log(`Wrote ${outputPath} (${Object.keys(schemas).length - SKIP_SCHEMAS.size} interface(s))`);
